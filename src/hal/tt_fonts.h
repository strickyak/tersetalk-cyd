inline FontSpec getFontSpec(uint8_t fontSize) {
  switch (fontSize) {
    case 8:  return {8,  6, 8,  7, 9,  kFontData6x8};
    case 9:  return {9,  7, 9,  8, 10, kFontData7x9};
    case 10: return {10, 8, 10, 9, 11, kFontData8x10};
    default: return {7,  5, 7,  6, 8,  kFontData5x7};
  }
}

inline const uint8_t* getGlyphRows(const FontSpec& spec, char ch) {
  uint8_t u = static_cast<uint8_t>(ch);
  if (u < 32 || u > 126) u = static_cast<uint8_t>('?');
  return spec.data + static_cast<unsigned>(u - 32) * spec.glyphH;
}

